using System.Text.Json;
using CadMcp.Providers;

namespace CadMcp.Tests;

public sealed class SubscriptionProcessDiscoveryTests
{
    private const string QwenPackage = "@qwen-code/qwen-code";
    private const string ShimComment = "REM Qwen Code current-session shim. Generated by install-qwen-standalone.ps1.";
    private static readonly string[] Arguments = ["--acp", "--auth-type", "qwen-subscription"];

    [Fact]
    public void Bare_legacy_Kimi_cmd_finds_the_native_exe_but_an_explicit_missing_path_is_never_replaced()
    {
        using var folder = new TempFolder();
        string executable = Write(folder.File("kimi.exe"), "native fixture; never executed");
        Assert.Equal(executable, SubscriptionProcess.ResolveExecutable("kimi.cmd", [folder.Path]));
        string missing = folder.File("kimi.cmd");
        var error = Assert.Throws<IOException>(() => SubscriptionProcess.ResolveExecutable(missing, [folder.Path]));
        Assert.StartsWith("CLI_NOT_FOUND", error.Message); Assert.Contains(missing, error.Message);
        Write(missing, "existing selected command");
        Assert.Equal(missing, SubscriptionProcess.ResolveExecutable("kimi.cmd", [folder.Path]));
    }

    [Theory]
    [InlineData("qwen")]
    [InlineData("kimi.cmd")]
    public void Missing_commands_report_CLI_discovery_failure_before_guessing_an_npm_package_in_the_working_directory(string command)
    {
        using var folder = new TempFolder();
        var error = Assert.Throws<IOException>(() => SubscriptionProcess.ResolveExecutable(command, [folder.Path]));
        Assert.StartsWith("CLI_NOT_FOUND", error.Message); Assert.Contains(command, error.Message);
        Assert.DoesNotContain("package.json", error.Message); Assert.DoesNotContain("node_modules", error.Message);
    }

    [Theory]
    [InlineData("qwen", "QWEN_INSTALL_BIN_DIR", "qwen.cmd")]
    [InlineData("kimi", "KIMI_INSTALL_DIR", "kimi.exe")]
    public void Public_discovery_finds_a_new_official_installation_without_restarting_the_host(string command, string variable, string filename)
    {
        using var folder = new TempFolder(); string bin = folder.File("new install/bin");
        string executable = Write(Path.Combine(bin, filename), "installation fixture; never executed");
        string? previous = Environment.GetEnvironmentVariable(variable);
        try
        {
            Environment.SetEnvironmentVariable(variable, command == "qwen" ? bin : Path.GetDirectoryName(bin));
            Assert.Equal(Path.GetFullPath(executable), SubscriptionCliSetup.FindExecutable(command));
        }
        finally { Environment.SetEnvironmentVariable(variable, previous); }
    }

    [Fact]
    public void Native_Kimi_executable_is_started_directly_with_original_argument_boundaries()
    {
        using var folder = new TempFolder(); string native = Write(folder.File("native & % path/kimi.exe"), "never executed");
        string[] arguments = ["acp", "--argument", "a path with spaces & percent%"];
        var info = SubscriptionProcess.Create(Options(folder, native), arguments, "@moonshot-ai/kimi-code", "kimi");
        Assert.Equal(Path.GetFullPath(native), info.FileName); Assert.Equal(arguments, info.ArgumentList);
        Assert.False(info.UseShellExecute); Assert.True(info.RedirectStandardInput); Assert.True(info.RedirectStandardOutput);
    }

    [Theory]
    [InlineData("node", false, false)]
    [InlineData("node", true, false)]
    [InlineData("node", true, true)]
    [InlineData("bun", false, false)]
    [InlineData("bun", true, true)]
    public void Qwen_standalone_and_official_forwarding_shims_resolve_the_bundled_runtime_without_cmd(string runtime, bool forwarding, bool comment)
    {
        using var folder = new TempFolder(); var installation = Standalone(folder, runtime, forwarding, comment);
        var info = SubscriptionProcess.Create(Options(folder, installation.Command), Arguments, QwenPackage, "qwen");
        Assert.Equal(installation.Runtime, info.FileName);
        Assert.Equal(new[] { installation.Entry }.Concat(Arguments), info.ArgumentList);
        Assert.Equal(installation.InternalShim, info.Environment["QWEN_CODE_LAUNCHER_PATH"]);
        Assert.False(info.UseShellExecute); Assert.DoesNotContain("cmd.exe", info.FileName, StringComparison.OrdinalIgnoreCase);
    }

    [Fact]
    public void Qwen_standalone_manifest_defaults_to_node_and_Bun_renderer_defaults_do_not_override_the_environment()
    {
        using var folder = new TempFolder(); var node = Standalone(folder, "node");
        File.WriteAllText(node.Manifest, JsonSerializer.Serialize(new { name = QwenPackage, target = "win-x64" }));
        Assert.Equal(node.Runtime, SubscriptionProcess.Create(Options(folder, node.Command), Arguments, QwenPackage, "qwen").FileName);
        var bun = Standalone(folder, "bun");
        string? previous = Environment.GetEnvironmentVariable("QWEN_TUI_RENDERER");
        try
        {
            Environment.SetEnvironmentVariable("QWEN_TUI_RENDERER", null);
            Assert.Equal("opentui", SubscriptionProcess.Create(Options(folder, bun.Command), Arguments, QwenPackage, "qwen").Environment["QWEN_TUI_RENDERER"]);
            Environment.SetEnvironmentVariable("QWEN_TUI_RENDERER", "explicit-renderer");
            Assert.Equal("explicit-renderer", SubscriptionProcess.Create(Options(folder, bun.Command), Arguments, QwenPackage, "qwen").Environment["QWEN_TUI_RENDERER"]);
        }
        finally { Environment.SetEnvironmentVariable("QWEN_TUI_RENDERER", previous); }
    }

    [Theory]
    [InlineData(false, false)]
    [InlineData(false, true)]
    [InlineData(true, false)]
    [InlineData(true, true)]
    public void Global_adjacent_and_project_local_npm_shims_use_only_the_verified_package_bin(bool localBin, bool stringBin)
    {
        using var folder = new TempFolder(); var npm = Npm(folder, localBin);
        File.WriteAllText(npm.Manifest, stringBin
            ? JsonSerializer.Serialize(new { name = QwenPackage, bin = "dist/cli.js" })
            : Manifest(QwenPackage, "dist/cli.js"));
        var info = SubscriptionProcess.Create(Options(folder, npm.Command), Arguments, QwenPackage, "qwen");
        Assert.Equal(npm.Runtime, info.FileName); Assert.True(File.Exists(info.FileName));
        Assert.Equal(new[] { npm.Entry }.Concat(Arguments), info.ArgumentList); Assert.False(info.UseShellExecute);
    }

    [Theory]
    [InlineData("wrong-name")]
    [InlineData("missing-name")]
    [InlineData("invalid-json")]
    [InlineData("oversized")]
    [InlineData("missing-file")]
    [InlineData("invalid-bin")]
    public void Unverified_or_invalid_npm_manifests_are_rejected(string fault)
    {
        using var folder = new TempFolder(); var npm = Npm(folder);
        if (fault == "missing-file") File.Delete(npm.Manifest);
        else File.WriteAllText(npm.Manifest, fault switch
        {
            "wrong-name" => Manifest("@other/untrusted", "dist/cli.js"),
            "missing-name" => "{\"bin\":{\"qwen\":\"dist/cli.js\"}}",
            "invalid-json" => "{not-json",
            "oversized" => new string(' ', 128 * 1024 + 1),
            _ => JsonSerializer.Serialize(new { name = QwenPackage, bin = 42 })
        });
        Assert.Throws<IOException>(() => SubscriptionProcess.Create(Options(folder, npm.Command), Arguments, QwenPackage, "qwen"));
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public void An_existing_entrypoint_outside_the_package_is_rejected(bool absolute)
    {
        using var folder = new TempFolder(); var npm = Npm(folder);
        string outside = Write(folder.File("outside.js"), "must not be selected");
        File.WriteAllText(npm.Manifest, Manifest(QwenPackage, absolute ? outside : Path.GetRelativePath(Path.GetDirectoryName(npm.Manifest)!, outside)));
        Assert.Throws<IOException>(() => SubscriptionProcess.Create(Options(folder, npm.Command), Arguments, QwenPackage, "qwen"));
    }

    [Fact]
    public void Missing_entrypoint_or_Node_is_rejected_before_a_process_can_be_started()
    {
        using var folder = new TempFolder(); var installation = Standalone(folder, "node");
        File.Delete(installation.Entry);
        Assert.Throws<IOException>(() => SubscriptionProcess.Create(Options(folder, installation.Command), Arguments, QwenPackage, "qwen"));
        Write(installation.Entry, "valid entry fixture"); File.Delete(installation.Runtime);
        var error = Assert.Throws<IOException>(() => SubscriptionProcess.Create(Options(folder, installation.Command), Arguments, QwenPackage, "qwen"));
        Assert.StartsWith("CLI_NOT_FOUND", error.Message); Assert.Contains("node", error.Message, StringComparison.OrdinalIgnoreCase);
    }

    [Fact]
    public async Task Forwarding_cycles_are_rejected_with_a_bounded_number_of_resolutions()
    {
        using var folder = new TempFolder(); string a = folder.File("a/qwen.cmd"), b = folder.File("b/qwen.cmd");
        Write(a, "@echo off\ncall \"" + b + "\" %*\n"); Write(b, "@echo off\ncall \"" + a + "\" %*\n");
        await Assert.ThrowsAsync<IOException>(async () => await Task.Run(() => SubscriptionProcess.Create(Options(folder, a), Arguments, QwenPackage, "qwen")).WaitAsync(TimeSpan.FromSeconds(5)));
    }

    [Theory]
    [InlineData("qwen", "https://qwen-code-assets.oss-cn-hangzhou.aliyuncs.com/installation/install-qwen-standalone.ps1")]
    [InlineData("kimi", "https://code.kimi.com/kimi-code/install.ps1")]
    public void Installer_start_info_contains_only_the_fixed_official_command_without_policy_bypass(string command, string url)
    {
        var info = SubscriptionCliSetup.CreateInstallStartInfo(command);
        Assert.Equal("powershell.exe", Path.GetFileName(info.FileName));
        Assert.Equal(new[] { "-NoProfile", "-NoExit", "-Command", "Invoke-RestMethod -Uri '" + url + "' | Invoke-Expression" }, info.ArgumentList);
        string arguments = string.Join(" ", info.ArgumentList);
        Assert.DoesNotContain("ExecutionPolicy", arguments, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("Bypass", arguments, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("EncodedCommand", arguments, StringComparison.OrdinalIgnoreCase);
    }

    [Theory]
    [InlineData("qwen; Write-Output injected")]
    [InlineData("https://other.example/install.ps1")]
    [InlineData("node")]
    public void Installer_selection_cannot_inject_a_script_or_change_the_download_host(string command) =>
        Assert.Throws<ArgumentException>(() => SubscriptionCliSetup.CreateInstallStartInfo(command));

    private static ProviderOptions Options(TempFolder folder, string executable) => TestEnvironment.ProviderOptions with { Executable = executable, WorkingDirectory = folder.Path };
    private static string Write(string path, string value)
    { Directory.CreateDirectory(Path.GetDirectoryName(path)!); File.WriteAllText(path, value); return path; }
    private static string Manifest(string name, string entry) => JsonSerializer.Serialize(new { name, bin = new Dictionary<string, string> { ["qwen"] = entry } });
    private sealed record Installation(string Command, string Runtime, string Entry, string Manifest, string InternalShim);
    private static Installation Standalone(TempFolder folder, string runtime, bool forwarding = false, bool comment = false)
    {
        string root = folder.File("standalone " + runtime + " & percent% path");
        string shim = Write(Path.Combine(root, "bin", "qwen.cmd"), "@echo off\nexit /b 99\n");
        string manifest = Write(Path.Combine(root, "manifest.json"), JsonSerializer.Serialize(new { name = QwenPackage, target = "win-x64", runtime }));
        string executable = Write(Path.Combine(root, runtime, runtime + ".exe"), "bundled runtime; never executed");
        string entry = Write(Path.Combine(root, "lib", "cli-entry.js"), "standalone entry; never executed");
        string command = forwarding ? Write(Path.Combine(root, "qwen.cmd"), "@echo off\n" + (comment ? ShimComment + "\n" : "") + "call \"" + shim + "\" %*\n") : shim;
        return new(command, executable, entry, manifest, shim);
    }
    private static Installation Npm(TempFolder folder, bool localBin = false)
    {
        string root = folder.File("npm install & percent% path");
        string directory = localBin ? Path.Combine(root, "node_modules", ".bin") : root;
        string shim = Write(Path.Combine(directory, "qwen.cmd"), "npm shim; never execute it");
        string package = Path.Combine(root, "node_modules", "@qwen-code", "qwen-code");
        string manifest = Write(Path.Combine(package, "package.json"), Manifest(QwenPackage, "dist/cli.js"));
        string entry = Write(Path.Combine(package, "dist", "cli.js"), "npm entry; never executed");
        string executable = Write(Path.Combine(directory, OperatingSystem.IsWindows() ? "node.exe" : "node"), "node fixture; never executed");
        return new(shim, executable, entry, manifest, shim);
    }
}
